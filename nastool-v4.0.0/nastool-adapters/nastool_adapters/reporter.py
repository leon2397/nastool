class Reporter:
    """统一报告生成器"""

    def __init__(self, result: Any):
        self.result = result

    def _get_grade(self, score: int) -> str:
        if score >= 90:
            return "A"
        elif score >= 80:
            return "B"
        elif score >= 70:
            return "C"
        elif score >= 60:
            return "D"
        return "F"

    def _get_grade_text(self, score: int) -> str:
        grades = {
            "A": "优秀 (Excellent)",
            "B": "良好 (Good)",
            "C": "一般 (Fair)",
            "D": "较差 (Poor)",
            "F": "严重 (Critical)",
        }
        return grades.get(self._get_grade(score), "未知")

    def generate_terminal(self) -> str:
        """生成终端输出（彩色）"""
        lines = []
        lines.append("=" * 60)
        lines.append("hw-jet v6.0 诊断报告")
        lines.append("=" * 60)

        # 设备信息
        lines.append(f"\n设备: {self.result.device_family or 'Unknown'}")
        if self.result.device_model:
            lines.append(f"型号: {self.result.device_model}")

        # 健康评分
        score = self.result.score or 0
        grade = self._get_grade(score)
        grade_color = {"A": "\033[92m", "B": "\033[94m", "C": "\033[93m", "D": "\033[91m", "F": "\033[91m"}.get(grade, "")
        lines.append(f"\n健康评分: {grade_color}{score}/100 ({grade})\033[0m")

        if self.result.score_breakdown:
            lines.append("\n评分明细:")
            for k, v in self.result.score_breakdown.items():
                lines.append(f"  - {k}: {v}/25")

        # NPU/GPU 状态
        npu_status = self.result.npu_status or self.result.gpu_status or {}
        if npu_status:
            lines.append("\nNPU/GPU 状态:")
            if "average_util" in npu_status:
                lines.append(f"  - 平均利用率: {npu_status['average_util']}%")
            if "average_temp" in npu_status:
                lines.append(f"  - 平均温度: {npu_status['average_temp']}°C")
            if "device_count" in npu_status:
                lines.append(f"  - 设备数量: {npu_status['device_count']}")

        # 系统状态
        system = self.result.system or {}
        if system:
            lines.append("\n系统状态:")
            if "memory" in system:
                mem = system["memory"]
                lines.append(f"  - 内存: {mem.get('total_mb', 0):.0f}MB (使用率 {mem.get('util_pct', 0):.1f}%)")
            if "cpu_cores" in system:
                lines.append(f"  - CPU 核心: {system['cpu_cores']}")

        # 基准测试
        benchmark = self.result.benchmark or {}
        if benchmark.get("latency_ms"):
            lines.append(f"\n推理基准 ({benchmark.get('framework', 'Unknown')}):")
            lines.append(f"  - 延迟: {benchmark['latency_ms']:.2f} ms")
            lines.append(f"  - 吞吐: {benchmark.get('throughput_fps', 0):.1f} FPS")

        # 工具链
        tools = self.result.tools or {}
        if tools:
            lines.append("\n工具链:")
            for k, v in tools.items():
                if isinstance(v, bool) and v:
                    lines.append(f"  [OK] {k}")
                elif isinstance(v, str) and not k.endswith("_path"):
                    lines.append(f"  [OK] {k}: {v}")

        lines.append("\n" + "=" * 60)
        return "\n".join(lines)

    def generate_json(self) -> Dict[str, Any]:
        """生成 JSON 报告"""
        return {
            "device_family": self.result.device_family,
            "device_model": self.result.device_model,
            "score": self.result.score,
            "grade": self._get_grade(self.result.score or 0),
            "score_breakdown": self.result.score_breakdown,
            "npu_status": self.result.npu_status,
            "gpu_status": self.result.gpu_status,
            "system": self.result.system,
            "benchmark": self.result.benchmark,
            "tools": self.result.tools,
            "timestamp": datetime.now().isoformat(),
        }

    def generate_html(self) -> str:
        """生成 HTML 报告"""
        score = self.result.score or 0
        grade = self._get_grade(score)

        # 评分明细 HTML
        breakdown_html = ""
        if self.result.score_breakdown:
            labels = {
                "npu_util": "NPU 利用率",
                "npu_temp": "NPU 温度",
                "npu_mem": "NPU 内存",
                "sys_mem": "系统内存",
                "gpu_util": "GPU 利用率",
                "temp": "温度",
                "toolchain": "工具链",
            }
            for k, v in self.result.score_breakdown.items():
                label = labels.get(k, k)
                breakdown_html += f'<div class="breakdown-item"><div class="label">{label}</div><div class="value">{v}/25</div></div>\n'

        # 设备信息 HTML
        device_info_html = f"""
            <div class="info-item"><div class="label">设备族</div><div class="value">{self.result.device_family or 'Unknown'}</div></div>
            <div class="info-item"><div class="label">型号</div><div class="value">{self.result.device_model or 'Unknown'}</div></div>
        """

        # NPU/GPU 状态 HTML
        npu_status = self.result.npu_status or self.result.gpu_status or {}
        npu_info_html = ""
        if npu_status:
            if "device_count" in npu_status:
                npu_info_html += f'<div class="info-item"><div class="label">设备数量</div><div class="value">{npu_status["device_count"]}</div></div>'
            if "average_util" in npu_status:
                npu_info_html += f'<div class="info-item"><div class="label">平均利用率</div><div class="value">{npu_status["average_util"]}%</div></div>'
            if "average_temp" in npu_status:
                npu_info_html += f'<div class="info-item"><div class="label">平均温度</div><div class="value">{npu_status["average_temp"]}°C</div></div>'

        # 系统状态 HTML
        system = self.result.system or {}
        system_info_html = ""
        if system:
            if "memory" in system:
                mem = system["memory"]
                system_info_html += f'<div class="info-item"><div class="label">内存</div><div class="value">{mem.get("total_mb", 0):.0f}MB ({mem.get("util_pct", 0):.1f}% used)</div></div>'
            if "cpu_cores" in system:
                system_info_html += f'<div class="info-item"><div class="label">CPU 核心</div><div class="value">{system["cpu_cores"]}</div></div>'
            if "cpu_model" in system:
                system_info_html += f'<div class="info-item"><div class="label">CPU 型号</div><div class="value">{system["cpu_model"]}</div></div>'

        # 基准测试 HTML
        benchmark = self.result.benchmark or {}
        benchmark_info_html = ""
        if benchmark.get("latency_ms"):
            benchmark_info_html += f'<div class="info-item"><div class="label">延迟</div><div class="value">{benchmark["latency_ms"]:.2f} ms</div></div>'
            benchmark_info_html += f'<div class="info-item"><div class="label">吞吐</div><div class="value">{benchmark.get("throughput_fps", 0):.1f} FPS</div></div>'
            benchmark_info_html += f'<div class="info-item"><div class="label">框架</div><div class="value">{benchmark.get("framework", "Unknown")}</div></div>'
        else:
            benchmark_info_html = '<div class="info-item"><div class="label">状态</div><div class="value">未运行</div></div>'

        # 工具链 HTML
        tools = self.result.tools or {}
        tools_info_html = ""
        for k, v in tools.items():
            if isinstance(v, bool) and v:
                tools_info_html += f'<div class="info-item"><div class="label">{k}</div><div class="value status-ok">[OK] 可用</div></div>'
            elif isinstance(v, str) and not k.endswith("_path"):
                tools_info_html += f'<div class="info-item"><div class="label">{k}</div><div class="value">{v}</div></div>'

        return HTML_TEMPLATE.format(
            device_name=self.result.device_model or self.result.device_family or "Unknown",
            timestamp=datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            score=score,
            grade=grade,
            breakdown_html=breakdown_html,
            device_info_html=device_info_html,
            npu_info_html=npu_info_html,
            system_info_html=system_info_html,
            benchmark_info_html=benchmark_info_html,
            tools_info_html=tools_info_html,
        )

    def generate_markdown(self) -> str:
        """生成 Markdown 报告"""
        score = self.result.score or 0

        # 评分明细 Markdown
        breakdown_md = ""
        if self.result.score_breakdown:
            labels = {
                "npu_util": "NPU 利用率",
                "npu_temp": "NPU 温度",
                "npu_mem": "NPU 内存",
                "sys_mem": "系统内存",
                "gpu_util": "GPU 利用率",
                "temp": "温度",
                "toolchain": "工具链",
            }
            for k, v in self.result.score_breakdown.items():
                label = labels.get(k, k)
                breakdown_md += f"| {label} | {v}/25 |\n"

        # NPU/GPU 状态 Markdown
        npu_status = self.result.npu_status or self.result.gpu_status or {}
        npu_status_md = "```json\n" + json.dumps(npu_status, indent=2, ensure_ascii=False) + "\n```"

        # 系统状态 Markdown
        system = self.result.system or {}
        system_status_md = "```json\n" + json.dumps(system, indent=2, ensure_ascii=False) + "\n```"

        # 基准测试 Markdown
        benchmark = self.result.benchmark or {}
        if benchmark.get("latency_ms"):
            benchmark_md = f"- **框架**: {benchmark.get('framework', 'Unknown')}\n- **延迟**: {benchmark['latency_ms']:.2f} ms\n- **吞吐**: {benchmark.get('throughput_fps', 0):.1f} FPS"
        else:
            benchmark_md = "未运行"

        # 工具链 Markdown
        tools = self.result.tools or {}
        tools_md = ""
        for k, v in tools.items():
            if isinstance(v, bool):
                tools_md += f"- {'[OK]' if v else '[X]'} {k}\n"
            elif isinstance(v, str) and not k.endswith("_path"):
                tools_md += f"- [OK] {k}: {v}\n"

        return MARKDOWN_TEMPLATE.format(
            device_name=self.result.device_model or self.result.device_family or "Unknown",
            device_family=self.result.device_family or "Unknown",
            timestamp=datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            score=score,
            grade_text=self._get_grade_text(score),
            breakdown_md=breakdown_md,
            npu_status_md=npu_status_md,
            system_status_md=system_status_md,
            benchmark_md=benchmark_md,
            tools_md=tools_md,
        )

    def save(self, path: str, format: str = "json") -> None:
        """保存报告到文件"""
        content = ""
        if format == "json":
            content = json.dumps(self.generate_json(), indent=2, ensure_ascii=False)
        elif format == "html":
            content = self.generate_html()
        elif format == "md":
            content = self.generate_markdown()
        else:
            raise ValueError(f"Unsupported format: {format}")

        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        logger.info(f"[Reporter] Saved {format} report to {path}")
