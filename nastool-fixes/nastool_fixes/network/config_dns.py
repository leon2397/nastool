"""
fixes/network/config_dns.py - Fix DNS configuration
"""

import os
from ..base import Fix, FixResult
from ..registry import register_fix


@register_fix
class ConfigDNSFix(Fix):
    """Configure DNS to use Google DNS (8.8.8.8)"""

    fix_id = "config_dns"
    title = "Configure DNS"
    description = "Set DNS to Google (8.8.8.8) if DNS resolution fails"
    risk = "low"
    requires_root = True

    DNS_CONFIG = """# Generated by nastool
nameserver 8.8.8.8
nameserver 223.5.5.5
"""

    def is_applicable(self) -> bool:
        """Check if DNS fix is needed"""
        import socket

        try:
            socket.gethostbyname("baidu.com")
            return False  # DNS works, no fix needed
        except socket.gaierror:
            return True  # DNS fails, fix needed

    def run(self) -> FixResult:
        resolv_conf = "/etc/resolv.conf"
        backup_file = "/etc/resolv.conf.bak.nastool"

        commands_run = []
        changed_files = []

        # Backup existing config
        if os.path.exists(resolv_conf):
            success, output = self._run_command(f"cp {resolv_conf} {backup_file}")
            commands_run.append(f"cp {resolv_conf} {backup_file}")
            if success:
                changed_files.append(backup_file)

        # Write new DNS config
        try:
            with open(resolv_conf, "w") as f:
                f.write(self.DNS_CONFIG)
            changed_files.append(resolv_conf)

            # Verify DNS works now
            import socket

            socket.gethostbyname("baidu.com")

            return FixResult(
                fix_id=self.fix_id,
                success=True,
                message="DNS configured successfully (8.8.8.8, 223.5.5.5)",
                changed_files=changed_files,
                commands_run=commands_run,
                rollback_command=f"mv {backup_file} {resolv_conf}",
            )
        except Exception as e:
            return FixResult(
                fix_id=self.fix_id,
                success=False,
                message=f"Failed to configure DNS: {str(e)}",
                changed_files=changed_files,
                commands_run=commands_run,
                error=str(e),
            )
